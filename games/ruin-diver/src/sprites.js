/** Pad a shape's rows to one width, centered. */
export function shape(name) {
  const rows = SHAPES[name];
  if (!rows._norm) {
    const w = Math.max(...rows.map((r) => r.length));
    const out = rows.map((r) => {
      const pad = w - r.length, l = pad >> 1;
      return ".".repeat(l) + r + ".".repeat(pad - l);
    });
    out._norm = true;
    SHAPES[name] = out;
  }
  return SHAPES[name];
}

function hexToHsl(h) {
  let s = h.replace("#", "");
  if (s.length === 3) s = [...s].map((c) => c + c).join("");
  const r = parseInt(s.slice(0, 2), 16) / 255, g = parseInt(s.slice(2, 4), 16) / 255, b = parseInt(s.slice(4, 6), 16) / 255;
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2;
  if (mx === mn) return [0, 0, l];
  const d = mx - mn, sat = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn);
  const hue = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [hue / 6, sat, l];
}
function hslToHex(h, s, l) {
  const f = (n) => {
    const k = (n + h * 12) % 12, a = s * Math.min(l, 1 - l);
    return Math.round((l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1))) * 255).toString(16).padStart(2, "0");
  };
  return "#" + f(0) + f(8) + f(4);
}
const variantCache = {};
/** A variant's palette: every color turned round the hue wheel and pushed more vivid. */
export function variantPal(name) {
  if (!variantCache[name]) {
    const src = PALS[name], out = {};
    for (const [k, v] of Object.entries(src)) {
      if (k === "o") { out[k] = v; continue; }
      const [h, s, l] = hexToHsl(v);
      out[k] = hslToHex((h + 0.42) % 1, Math.min(1, s * 0.6 + 0.45), l);
    }
    variantCache[name] = out;
  }
  return variantCache[name];
}

const iconCache = new Map();
/**
 * A data URL of an item's sprite for the DOM. mode: "color", "silhouette" (unknown) or "dim" (seen, not owned).
 */
export function itemIcon(item, mode = "color", variant = false, scale = 4) {
  const key = item.id + mode + variant + scale;
  if (iconCache.has(key)) return iconCache.get(key);
  const rows = shape(item.sprite), pal = variant ? variantPal(item.pal) : PALS[item.pal];
  const h = rows.length, w = rows[0].length;
  const cv = document.createElement("canvas");
  cv.width = w * scale; cv.height = h * scale;
  const g = cv.getContext("2d");
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      if (ch === "." || ch === " ") continue;
      let c = pal[ch] ?? "#ff00ff";
      if (mode === "silhouette") c = ch === "o" ? "#3a3448" : "#1c1826";
      else if (mode === "dim") c = ch === "o" ? "#2a2434" : "#4a4458";
      g.fillStyle = c;
      g.fillRect(x * scale, y * scale, scale, scale);
    }
  const url = cv.toDataURL();
  iconCache.set(key, url);
  return url;
}
